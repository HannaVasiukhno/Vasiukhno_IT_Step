# Завдання 7
# Користувач вводить пароль поки не введе його
# правильно.
# Правильний пароль повинен:
# ● Бути довшим за 8 символів
# ● Містити хоча б одну цифру
# ● Містити хоча б одну літеру

# Цикл
while True:
    # Кожну ітерацію мусимо перезаписувати змінні
    isnumber = 0
    isletter = 0
    password = input("Введіть пароль: ")

    # Перевіряємо одразу і наявність літер і цифр
    for ch in password:
        if ch.isdigit():
            isnumber += 1
        elif ch.isalpha():
            isletter += 1

        # Зупиняємо цикл якщо є і то і то
        if isnumber > 0 and isletter > 0:
            break

    if len(password) > 8 and isnumber > 0 and isletter > 0:
        print("Пароль правильний")
        break

    # Важливо перевірити пароль на 3 вимоги і повідомити про всі наявні помилки одразу
    if len(password) <= 8:
        print("Пароль має бути довшим за 8 символів")
    if isnumber == 0:
        print("Пароль має містити хоча б одну цифру")
    if isletter == 0:
        print("Пароль має містити хоча б одну літеру")
